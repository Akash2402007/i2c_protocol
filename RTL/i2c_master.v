`timescale 1ns / 1ps

`timescale 1ns / 1ps

module i2c_master (
    input wire clk,             // System clock: controls FSM operation
    input wire rst_n,           // Active-low asynchronous reset
    input wire start,           // Start I2C transmission when HIGH
    input wire [6:0] addr,      // 7-bit slave address
    input wire [7:0] data,      // 8-bit data to transmit

    output reg scl,             // I2C serial clock generated by master
    inout wire sda,             // Bidirectional I2C data line
    output reg busy             // HIGH while transmission is active
);


// =================================================
// 1. REGISTER DECLARATIONS
// =================================================

// Stores the current FSM state
reg [3:0] state;

// Selects the bit being transmitted
// 7 = MSB, 0 = LSB
reg [3:0] bit_cnt;

// Controls the timing sequence of each I2C bit
// Phase 0 = SCL LOW, prepare SDA
// Phase 1 = SCL HIGH, receiver samples SDA
// Phase 2 = SCL LOW, complete the bit
reg [1:0] phase;

// Controls the open-drain SDA output
// 1 = Pull SDA LOW
// 0 = Release SDA (pull-up resistor makes it HIGH)
reg sda_oe;

// Stores the complete address frame
// tx_byte[7:1] = 7-bit slave address
// tx_byte[0]   = R/W bit (0 = WRITE)
reg [7:0] tx_byte;


// =================================================
// 2. OPEN-DRAIN SDA IMPLEMENTATION
// =================================================

// I2C devices must not actively drive SDA HIGH.
// The master either pulls SDA LOW or releases it.
//
// When sda_oe = 1, SDA becomes LOW.
// When sda_oe = 0, SDA becomes high impedance (Z).
// An external pull-up resistor brings SDA HIGH.

assign sda = sda_oe ? 1'b0 : 1'bz;


// =================================================
// 3. FSM STATE DEFINITIONS
// =================================================

localparam IDLE  = 4'd0,  // Wait for transmission request
           START = 4'd1,  // Generate START condition
           ADDR  = 4'd2,  // Transmit address + R/W bit
           ACK1  = 4'd3,  // Receive address acknowledgement
           DATA  = 4'd4,  // Transmit 8-bit data
           ACK2  = 4'd5,  // Receive data acknowledgement
           STOP  = 4'd6,  // Generate STOP condition
           NACK  = 4'd7;  // Handle missing acknowledgement


// =================================================
// 4. SEQUENTIAL FSM
// =================================================

// All FSM operations and register updates occur
// on the rising edge of the system clock.
//
// The reset is asynchronous and active LOW.

always @(posedge clk or negedge rst_n) begin

    // ---------------------------------------------
    // ASYNCHRONOUS RESET
    // ---------------------------------------------

    if (!rst_n) begin

        state   <= IDLE;       // Return FSM to idle
        scl     <= 1'b1;       // I2C clock is HIGH when idle
        sda_oe  <= 1'b0;       // Release SDA
        bit_cnt <= 0;          // Clear bit counter
        phase   <= 0;          // Reset timing phase
        tx_byte <= 0;          // Clear address register
        busy    <= 1'b0;       // No transmission active

    end

    else begin

        case (state)


            // =====================================
            // STATE 1: IDLE
            // =====================================

            IDLE: begin

                // Both I2C lines remain HIGH in idle.
                // SDA is released and SCL is HIGH.

                scl     <= 1'b1;
                sda_oe  <= 1'b0;
                busy    <= 1'b0;
                phase   <= 0;

                // Wait until the master receives a start request
                if (start) begin

                    busy <= 1'b1;

                    // Combine the 7-bit address with R/W = 0.
                    // This makes an 8-bit address frame.
                    // The master will perform a WRITE operation.

                    tx_byte <= {addr, 1'b0};

                    state <= START;

                end

            end


            // =====================================
            // STATE 2: START CONDITION
            // =====================================

            START: begin

                // START condition:
                // SDA transitions from HIGH to LOW
                // while SCL remains HIGH.

                scl    <= 1'b1;
                sda_oe <= 1'b1;

                // Initialize the bit counter to 7.
                // Address transmission starts from the MSB.

                bit_cnt <= 7;

                phase <= 0;

                state <= ADDR;

            end


            // =====================================
            // STATE 3: ADDRESS TRANSMISSION
            // =====================================

            ADDR: begin

                case (phase)

                    // ---------------------------------
                    // PHASE 0: SCL LOW
                    // ---------------------------------

                    0: begin

                        // Pull SCL LOW before changing SDA.
                        // Select the current address-frame bit.

                        scl <= 1'b0;

                        // If current bit is 0, pull SDA LOW.
                        // If current bit is 1, release SDA.

                        sda_oe <= ~tx_byte[bit_cnt];

                        phase <= 1;

                    end


                    // ---------------------------------
                    // PHASE 1: SCL HIGH
                    // ---------------------------------

                    1: begin

                        // Raise SCL HIGH.
                        // Slave reads the address-frame bit
                        // while SCL is HIGH.

                        scl <= 1'b1;

                        phase <= 2;

                    end


                    // ---------------------------------
                    // PHASE 2: SCL LOW
                    // ---------------------------------

                    2: begin

                        // Bring SCL LOW to complete this bit.
                        // The next bit can now be prepared.

                        scl <= 1'b0;

                        phase <= 0;

                        if (bit_cnt == 0) begin

                            // All 8 bits have been transmitted:
                            // 7 address bits + 1 R/W bit.

                            state <= ACK1;

                        end

                        else begin

                            // Select the next bit.
                            // Transmission is MSB first.

                            bit_cnt <= bit_cnt - 1'b1;

                        end

                    end

                endcase

            end


            // =====================================
            // STATE 4: FIRST ACKNOWLEDGEMENT
            // =====================================

            ACK1: begin

                case (phase)

                    // ---------------------------------
                    // PHASE 0: RELEASE SDA
                    // ---------------------------------

                    0: begin

                        // SCL is LOW.
                        // Master releases SDA so the slave
                        // can generate ACK or NACK.

                        scl    <= 1'b0;
                        sda_oe <= 1'b0;

                        phase <= 1;

                    end


                    // ---------------------------------
                    // PHASE 1: ACK CLOCK PULSE
                    // ---------------------------------

                    1: begin

                        // Raise SCL HIGH.
                        // Slave pulls SDA LOW for ACK.
                        // SDA remains released by the master.

                        scl <= 1'b1;

                        phase <= 2;

                    end


                    // ---------------------------------
                    // PHASE 2: SAMPLE ACK/NACK
                    // ---------------------------------

                    2: begin

                        // Sample SDA while SCL is still HIGH.
                        // Then bring SCL LOW.

                        scl <= 1'b0;

                        phase <= 0;

                        if (sda == 1'b0) begin

                            // SDA LOW means ACK.
                            // Slave has acknowledged the address.

                            bit_cnt <= 7;

                            state <= DATA;

                        end

                        else begin

                            // SDA HIGH means NACK.
                            // Slave did not acknowledge the address.

                            state <= NACK;

                        end

                    end

                endcase

            end


            // =====================================
            // STATE 5: DATA TRANSMISSION
            // =====================================

            DATA: begin

                case (phase)

                    // ---------------------------------
                    // PHASE 0: SCL LOW
                    // ---------------------------------

                    0: begin

                        // SCL LOW allows the master to
                        // change the data line safely.

                        scl <= 1'b0;

                        // Transmit the current data bit.
                        // 0 = Pull SDA LOW.
                        // 1 = Release SDA.

                        sda_oe <= ~data[bit_cnt];

                        phase <= 1;

                    end


                    // ---------------------------------
                    // PHASE 1: SCL HIGH
                    // ---------------------------------

                    1: begin

                        // Raise SCL HIGH.
                        // Slave samples the current data bit.

                        scl <= 1'b1;

                        phase <= 2;

                    end


                    // ---------------------------------
                    // PHASE 2: SCL LOW
                    // ---------------------------------

                    2: begin

                        // Lower SCL to complete the current bit.

                        scl <= 1'b0;

                        phase <= 0;

                        if (bit_cnt == 0) begin

                            // All 8 data bits have been transmitted.
                            // Next, wait for the slave acknowledgement.

                            state <= ACK2;

                        end

                        else begin

                            // Move to the next data bit.

                            bit_cnt <= bit_cnt - 1'b1;

                        end

                    end

                endcase

            end


            // =====================================
            // STATE 6: SECOND ACKNOWLEDGEMENT
            // =====================================

            ACK2: begin

                case (phase)

                    // ---------------------------------
                    // PHASE 0: RELEASE SDA
                    // ---------------------------------

                    0: begin

                        // Release SDA for the slave response.
                        // SCL remains LOW.

                        scl    <= 1'b0;
                        sda_oe <= 1'b0;

                        phase <= 1;

                    end


                    // ---------------------------------
                    // PHASE 1: ACK CLOCK PULSE
                    // ---------------------------------

                    1: begin

                        // Raise SCL HIGH.
                        // Slave generates ACK or NACK.

                        scl <= 1'b1;

                        phase <= 2;

                    end


                    // ---------------------------------
                    // PHASE 2: SAMPLE ACK/NACK
                    // ---------------------------------

                    2: begin

                        // Sample SDA while SCL is HIGH.
                        // Then lower SCL.

                        scl <= 1'b0;

                        phase <= 0;

                        if (sda == 1'b0)

                            // Data byte successfully acknowledged.
                            // Generate STOP condition.

                            state <= STOP;

                        else

                            // Slave did not acknowledge data.
                            // Handle NACK.

                            state <= NACK;

                    end

                endcase

            end


            // =====================================
            // STATE 7: NACK HANDLING
            // =====================================

            NACK: begin

                // The slave did not acknowledge the
                // address or data byte.

                // Prepare the bus for a STOP condition.
                // Keep SCL LOW and pull SDA LOW.

                scl    <= 1'b0;
                sda_oe <= 1'b1;

                phase <= 0;

                // Generate STOP before returning to IDLE.

                state <= STOP;

            end


            // =====================================
            // STATE 8: STOP CONDITION
            // =====================================

            STOP: begin

                case (phase)

                    // ---------------------------------
                    // PHASE 0: SDA LOW, SCL LOW
                    // ---------------------------------

                    0: begin

                        // Ensure SDA is LOW.
                        // Keep SCL LOW before STOP generation.

                        scl    <= 1'b0;
                        sda_oe <= 1'b1;

                        phase <= 1;

                    end


                    // ---------------------------------
                    // PHASE 1: RAISE SCL
                    // ---------------------------------

                    1: begin

                        // Raise SCL HIGH while SDA remains LOW.

                        scl <= 1'b1;

                        phase <= 2;

                    end


                    // ---------------------------------
                    // PHASE 2: RELEASE SDA
                    // ---------------------------------

                    2: begin

                        // Release SDA while SCL is HIGH.
                        // SDA transitions LOW to HIGH.
                        // This generates the STOP condition.

                        scl    <= 1'b1;
                        sda_oe <= 1'b0;

                        // Transmission is now complete.

                        busy <= 1'b0;

                        phase <= 0;

                        state <= IDLE;

                    end

                endcase

            end


            // =====================================
            // DEFAULT STATE
            // =====================================

            default: begin

                // Recover to the idle bus condition
                // if an undefined FSM state occurs.

                state   <= IDLE;
                scl     <= 1'b1;
                sda_oe  <= 1'b0;
                busy    <= 1'b0;
                phase   <= 0;
                bit_cnt <= 0;

            end

        endcase

    end

end

endmodule

